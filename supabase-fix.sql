DO $$
BEGIN
  IF to_regclass('public.waitlist') IS NULL
     AND to_regclass('public."flekvar/waitlist"') IS NOT NULL THEN
    ALTER TABLE public."flekvar/waitlist" RENAME TO waitlist;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.waitlist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.waitlist ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "allow public inserts" ON public.waitlist;

CREATE POLICY "allow public inserts"
ON public.waitlist
FOR INSERT
TO anon
WITH CHECK (true);

DROP POLICY IF EXISTS "allow public reads" ON public.waitlist;

CREATE POLICY "allow public reads"
ON public.waitlist
FOR SELECT
TO anon
USING (true);

CREATE UNIQUE INDEX IF NOT EXISTS waitlist_email_unique
ON public.waitlist(email);
